"""Comprehensive validation suite with thermodynamic/topological/geometric proxies.

The script generates a reproducible synthetic dataset and evaluates a collection
of metrics that act as lightweight stand-ins for the research validations
referenced in the project documentation. The resulting metrics are written to a
JSON file whose location is provided via ``--out``.
"""
from __future__ import annotations

import argparse
import json
import math
import statistics
from dataclasses import asdict, dataclass
from pathlib import Path
from random import Random
from typing import Dict, Iterable, List


@dataclass
class ComprehensiveMetrics:
    """Container for the metrics generated by the suite."""

    energy_efficiency: float
    entropy: float
    fractal_dimension: float
    curvature: float
    topological_complexity: float
    stability_index: float

    def as_serializable(self) -> Dict[str, float]:
        return {key: float(value) for key, value in asdict(self).items()}


def _gaussian_series(size: int, seed: int) -> List[float]:
    rng = Random(seed)
    return [rng.gauss(0.0, 1.0) for _ in range(size)]


def _normalize(series: Iterable[float]) -> List[float]:
    seq = list(series)
    minimum = min(seq)
    maximum = max(seq)
    if math.isclose(minimum, maximum):
        return [0.5 for _ in seq]
    span = maximum - minimum
    return [(value - minimum) / span for value in seq]


def _shannon_entropy(series: Iterable[float], bins: int = 20) -> float:
    normalized = _normalize(series)
    counts = [0 for _ in range(bins)]
    for value in normalized:
        index = min(int(value * bins), bins - 1)
        counts[index] += 1
    total = float(len(normalized))
    entropy = 0.0
    for count in counts:
        if count == 0:
            continue
        probability = count / total
        entropy -= probability * math.log(probability, 2)
    return entropy


def _box_count_fractal_dimension(series: Iterable[float], resolutions: Iterable[int]) -> float:
    normalized = _normalize(series)
    counts: List[float] = []
    scales: List[float] = []
    for resolution in resolutions:
        if resolution <= 0:
            continue
        boxes = [0 for _ in range(resolution)]
        for value in normalized:
            index = min(int(value * resolution), resolution - 1)
            boxes[index] += 1
        occupied = sum(1 for count in boxes if count > 0)
        if occupied == 0:
            continue
        counts.append(math.log(occupied))
        scales.append(math.log(1.0 / resolution))
    if len(counts) < 2:
        return 0.0
    slope = _least_squares_slope(scales, counts)
    return max(0.0, slope)


def _least_squares_slope(xs: Iterable[float], ys: Iterable[float]) -> float:
    x_values = list(xs)
    y_values = list(ys)
    if len(x_values) != len(y_values) or not x_values:
        return 0.0
    x_mean = statistics.mean(x_values)
    y_mean = statistics.mean(y_values)
    numerator = sum((x - x_mean) * (y - y_mean) for x, y in zip(x_values, y_values))
    denominator = sum((x - x_mean) ** 2 for x in x_values)
    if math.isclose(denominator, 0.0):
        return 0.0
    return numerator / denominator


def _curvature(series: Iterable[float]) -> float:
    values = list(series)
    if len(values) < 3:
        return 0.0
    curvature_samples: List[float] = []
    for i in range(1, len(values) - 1):
        prev_value = values[i - 1]
        current_value = values[i]
        next_value = values[i + 1]
        second_derivative = next_value - 2 * current_value + prev_value
        curvature_samples.append(abs(second_derivative))
    return statistics.mean(curvature_samples)


def _topological_complexity(series: Iterable[float]) -> float:
    values = list(series)
    if len(values) < 2:
        return 0.0
    zero_crossings = 0
    for first, second in zip(values, values[1:]):
        if first == 0:
            continue
        if first * second <= 0:
            zero_crossings += 1
    oscillation_ratio = zero_crossings / (len(values) - 1)
    return oscillation_ratio


def _stability_index(series: Iterable[float]) -> float:
    values = list(series)
    if len(values) < 2:
        return 1.0
    rolling_variances: List[float] = []
    window = max(5, len(values) // 20)
    for start in range(0, len(values) - window + 1):
        window_slice = values[start : start + window]
        rolling_variances.append(statistics.pvariance(window_slice))
    mean_variance = statistics.mean(rolling_variances)
    total_variance = statistics.pvariance(values)
    if math.isclose(total_variance, 0.0):
        return 1.0
    stability = 1.0 - min(1.0, mean_variance / total_variance)
    return max(0.0, stability)


def run_suite(series_size: int, seed: int) -> ComprehensiveMetrics:
    series = _gaussian_series(series_size, seed)
    energy_efficiency = 1.0 / (1.0 + statistics.pvariance(series))
    entropy = _shannon_entropy(series)
    fractal_dimension = _box_count_fractal_dimension(series, resolutions=range(4, 40, 4))
    curvature = _curvature(series)
    topological_complexity = _topological_complexity(series)
    stability_index = _stability_index(series)
    return ComprehensiveMetrics(
        energy_efficiency=energy_efficiency,
        entropy=entropy,
        fractal_dimension=fractal_dimension,
        curvature=curvature,
        topological_complexity=topological_complexity,
        stability_index=stability_index,
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run the comprehensive validation suite.")
    parser.add_argument("--out", type=Path, required=True, help="Path to the JSON file that will store the metrics.")
    parser.add_argument(
        "--size",
        type=int,
        default=2048,
        help="Number of samples to generate for the synthetic evaluation series (default: 2048).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=1337,
        help="Seed for the pseudo-random generator to ensure reproducibility (default: 1337).",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    metrics = run_suite(series_size=args.size, seed=args.seed)
    payload = {
        "metrics": metrics.as_serializable(),
        "metadata": {
            "series_size": args.size,
            "seed": args.seed,
            "generator": "gaussian",
        },
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(payload, indent=2))


if __name__ == "__main__":
    main()
